const DICT = { pl: PL, en: EN };

function fill(s, vars) {
  return String(s).replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] !== undefined ? String(vars[k]) : m));
}

/** Zwraca funkcje tłumaczące dla danego języka (domyślnie polski). */
export function translator(lang) {
  const code = DICT[lang] ? lang : 'pl';
  const dict = DICT[code];
  const rules = new Intl.PluralRules(code);
  const t = (key, vars) => {
    const v = dict[key] !== undefined ? dict[key] : PL[key];
    return v === undefined ? key : typeof v === 'string' ? fill(v, vars) : v;
  };
  const tn = (key, n, vars) => {
    const forms = dict[key] || PL[key];
    if (!forms || typeof forms !== 'object') return fill(key, { n });
    const f = forms[rules.select(n)] || forms.other || forms.many;
    return fill(f, { n, ...(vars || {}) });
  };
  const money = (v) =>
    code === 'en'
      ? `PLN ${new Intl.NumberFormat('en-GB', { maximumFractionDigits: 0 }).format(v)}`
      : new Intl.NumberFormat('pl-PL', { maximumFractionDigits: 0, useGrouping: true }).format(v).replace(/\s/g, ' ') + ' zł';
  return { lang: code, t, tn, money };
}

/** Język przeglądarki: polski dla „pl”, w pozostałych przypadkach angielski. */
export function detectLang(languages) {
  const list = (languages && languages.length ? languages : ['pl']).map((l) => String(l).toLowerCase());
  return list[0].startsWith('pl') ? 'pl' : 'en';
}

export function hasKey(key, lang = 'pl') {
  return DICT[lang] && DICT[lang][key] !== undefined;
}

export function keys(lang = 'pl') {
  return Object.keys(DICT[lang] || {});
}
